"""Re-run our current result check on every recorded live result (results/live/*.img), with no API calls.

For each result it also runs a negative control: the same real image with red and blue swapped (a wrong-colour
garment) must be held back. Writes results/RECHECK.md and refreshes each recorded result's care-label fields
(findings, verdict, swatches, description) so replays show the current check. Latency fields are kept as measured.

  python tools/recheck_live.py
"""
import io
import json
import pathlib
import sys

import numpy as np
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import checks  # noqa: E402

CATALOG = {g["id"]: g for g in json.loads((ROOT / "catalog.json").read_text())}


def wrong_colour(result, photo):
    """The same real result with red and blue swapped only where the try-on changed the photo (the garment
    area), like a model that got the garment's colour wrong. The backdrop and the person stay as they were."""
    r = np.asarray(Image.open(io.BytesIO(result)).convert("RGB"))
    p = np.asarray(Image.open(io.BytesIO(photo)).convert("RGB").resize((r.shape[1], r.shape[0])))
    changed = np.abs(r.astype(int) - p.astype(int)).mean(-1) > 30
    out = r.copy()
    out[changed] = r[changed][:, ::-1]
    return Image.fromarray(out)


def main():
    rows, bad = [], 0
    for meta_path in sorted((ROOT / "results/live").glob("*.json")):
        sample, garment = meta_path.stem.split("__")
        meta = json.loads(meta_path.read_text())
        result = (ROOT / f"results/live/{meta_path.stem}.img").read_bytes()
        photo = next((ROOT / "static/models").glob(f"{sample}.*")).read_bytes()
        _, clean = checks.photo_check(photo)  # the exact bytes the API received
        garment_png = (ROOT / f"static/garments/{garment}.png").read_bytes()
        c = checks.result_check(garment_png, clean, result)
        swapped = io.BytesIO()
        wrong_colour(result, clean).save(swapped, "JPEG", quality=92)
        control = checks.result_check(garment_png, clean, swapped.getvalue())
        bad += control["verdict_ok"]
        old = meta.get("first_verdict", meta["verdict"])
        new = "shown" if c["verdict_ok"] else "held back"
        rows.append(f"| {sample} | {garment} | {old} ({meta.get('first_colour_score', meta['colour_score'])}) | {new} ({c['colour_score']}) | "
                    f"{'caught' if not control['verdict_ok'] else 'MISSED'} ({control['colour_score']}) |")
        meta.setdefault("first_verdict", meta["verdict"])
        meta.setdefault("first_colour_score", meta["colour_score"])
        meta.update(findings=c["findings"], colour_score=c["colour_score"], swatches=c["swatches"], verdict=new,
                    description=checks.describe(CATALOG[garment], c, new))
        meta_path.write_text(json.dumps(meta, indent=1))
    text = "\n".join([
        "# Re-check of recorded live results", "",
        "Generated by `python tools/recheck_live.py` from the images in `results/live/` (made by the Clothsy AI API).",
        "No API calls. \"At the time\" is the check that ran during the live run; \"now\" is the current check.",
        "The negative control swaps red and blue in the same real image, only where the try-on changed the photo",
        "(the garment area): a wrong-colour garment on an unchanged backdrop. Our check must hold it back.", "",
        "| Sample photo | Garment | At the time (colour score) | Now (colour score) | Wrong-colour control |",
        "|---|---|---|---|---|", *rows, "",
        f"{len(rows)} results; negative controls missed: {bad}.", ""])
    (ROOT / "results/RECHECK.md").write_text(text)
    print(text)
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
