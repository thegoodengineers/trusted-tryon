"""Measure try-on latency through our real pipeline (upload, API, checks, retry, cache) and write results/.

  python bench.py              # mock (no key): measures our own overhead only, labelled "mock"
  python bench.py --real --n 1 # live API; needs HTF_TRYON_API_KEY. Each garment costs up to 2 credits per round.
  python scripts/live_check.py # the one-command live check (key and credits checked first)

Writes results/latency.csv (one row per try-on, appended) and results/LATENCY.md (summary of all rows).
Never hand-edit those files: every number in them comes from a run of this script.
"""
import argparse
import csv
import datetime
import os
import pathlib
import platform
import statistics
import subprocess
import time

from fastapi.testclient import TestClient

HERE = os.path.dirname(os.path.abspath(__file__))
FIELDS = ["when", "commit", "machine", "mode", "model", "garment", "photo_upload_s", "server_total_s", "wall_s",
          "attempts", "verdict", "colour_score", "ai_label", "cached_repeat_s", "polls", "http_retries"]


def load_app(real):
    """Import the app with the right client: live only when asked and a key is set."""
    if not real:
        os.environ.pop("HTF_TRYON_API_KEY", None)
        os.environ.setdefault("HTF_MOCK_DELAY", "0")
    os.environ["HTF_REPLAY"] = "0"  # always measure a fresh try-on, never a recorded replay
    os.chdir(HERE)
    import app as server
    return server


def run(server, pairs):
    """Try on each (model, garment) pair through the web API: one photo upload per model, then each of its
    garments, then the same pair again to time the cache. Returns one CSV row per try-on."""
    web = TestClient(server.app)
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip() or "none"
    machine = f"{platform.system()}-{platform.machine()}-{platform.node()[:12]}"
    rows = []
    for model in dict.fromkeys(m for m, _ in pairs):
        # A model is one of our sample figures, or a path to a consenting adult's photo kept outside the repo.
        is_path = os.path.isfile(model)
        photo = open(model if is_path else next(pathlib.Path("static/models").glob(f"{model}.*")), "rb").read()
        label = "own-photo" if is_path else model  # never write a personal file path into results
        t = time.perf_counter()
        up = web.post("/api/photo", files={"photo": ("p.png", photo, "image/png")}, data={"consent": "true", "adult": "true"})
        up.raise_for_status()
        sid, upload_s = up.json()["session"], time.perf_counter() - t
        for gid in [g for m, g in pairs if m == model]:
            t = time.perf_counter()
            job = web.post("/api/tryon", json={"session": sid, "garment": gid}).json()["job"]
            while not (j := web.get(f"/api/tryon/{job}").json())["done"]:
                time.sleep(0.2)
            wall = time.perf_counter() - t
            t = time.perf_counter()
            job2 = web.post("/api/tryon", json={"session": sid, "garment": gid}).json()["job"]
            cached = web.get(f"/api/tryon/{job2}").json().get("cached", False)
            cached_s = time.perf_counter() - t
            ai = next((f["ok"] for f in j.get("findings", []) if f["id"] == "label"), "")
            row = {"when": datetime.datetime.now().isoformat(timespec="seconds"), "commit": commit, "machine": machine,
                   "mode": j.get("mode", server.client.mode), "model": label, "garment": gid, "photo_upload_s": round(upload_s, 3),
                   "server_total_s": j.get("total_seconds"), "wall_s": round(wall, 3),
                   "attempts": len(j.get("attempts", [])),
                   "verdict": j.get("verdict") or j.get("error", {}).get("code"), "colour_score": j.get("colour_score"),
                   "ai_label": ai, "cached_repeat_s": round(cached_s, 4) if cached else "",
                   "polls": sum(a.get("polls", 0) for a in j.get("attempts", [])),
                   "http_retries": sum(a.get("http_retries", 0) for a in j.get("attempts", []))}
            rows.append(row)
            print(row)
        web.delete(f"/api/session/{sid}")  # forgetting the photo also clears its cache, so the next round is cold
    return rows


def pct(values, p):
    """Nearest-rank percentile."""
    v = sorted(float(x) for x in values)
    return v[max(0, min(len(v) - 1, -(-p * len(v) // 100) - 1))]


def write(rows):
    os.makedirs("results", exist_ok=True)
    path = "results/latency.csv"
    new = not os.path.exists(path)
    with open(path, "a", newline="") as f:
        w = csv.DictWriter(f, FIELDS)
        if new:
            w.writeheader()
        w.writerows(rows)
    summarise(path)


def summarise(path):
    rows = list(csv.DictReader(open(path)))
    out = ["# Try-on latency", "",
           "Generated by `python bench.py` and `python scripts/live_check.py` from `results/latency.csv`. Do not edit by hand.",
           "Wall time = click to checked result, including any retry, over try-ons that produced an image. Requests the API",
           "refused before generating anything (no credit used) are counted separately.", "",
           "| Mode | Try-ons asked | Produced an image | p50 wall (s) | p95 wall (s) | Median cached repeat (s) | Shown first time | Retried and passed | Held back | Refused by the API | AI label in file |",
           "|---|---|---|---|---|---|---|---|---|---|---|"]
    finished = ("shown", "retried", "held back")
    for mode in sorted({r["mode"] for r in rows}):
        rs = [r for r in rows if r["mode"] == mode]
        done = [r for r in rs if r["verdict"] in finished]
        walls = [r["wall_s"] for r in done]
        p50, p95 = (f"{pct(walls, 50):.2f}", f"{pct(walls, 95):.2f}") if walls else ("-", "-")
        count = lambda v: sum(r["verdict"] == v for r in rs)
        refused = {}
        for r in rs:
            if r["verdict"] not in finished:
                refused[r["verdict"]] = refused.get(r["verdict"], 0) + 1
        refused_cell = ", ".join(f"{n} {code}" for code, n in refused.items()) or "0"
        cached = [float(r["cached_repeat_s"]) for r in rs if r.get("cached_repeat_s")]
        cache_cell = f"{statistics.median(cached):.4f}" if cached else "-"
        labelled = sum(r.get("ai_label") == "True" for r in done)
        out.append(f"| {mode} | {len(rs)} | {len(done)} | {p50} | {p95} | {cache_cell} | {count('shown')} | {count('retried')} | "
                   f"{count('held back')} | {refused_cell} | {labelled} of {len(done)} |")
    out += ["", "Mock rows measure only our own pipeline (upload, checks, retry, cache) around a paste-on stand-in, plus a "
            "deliberate colour fault on the kurta's first try after each server start. They say nothing about the real API's "
            "speed or accuracy. Live rows come from the Clothsy AI API.",
            "", f"Last run: {rows[-1]['when']} on {rows[-1]['machine']}, commit {rows[-1]['commit']}."]
    text = "\n".join(out) + "\n"
    open("results/LATENCY.md", "w").write(text)
    print(text)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--real", action="store_true", help="use the live API (HTF_TRYON_API_KEY must be set)")
    ap.add_argument("--n", type=int, default=3, help="rounds over all garments")
    ap.add_argument("--garments", default="", help="comma-separated ids (default: all)")
    args = ap.parse_args()
    if args.real and not os.environ.get("HTF_TRYON_API_KEY"):
        raise SystemExit("Set HTF_TRYON_API_KEY first (see README).")
    server = load_app(args.real)
    garments = args.garments.split(",") if args.garments else list(server.CATALOG)
    rows = []
    for _ in range(args.n):
        rows += run(server, [(m, g) for m in ("asha", "ravi") for g in garments])
    write(rows)


if __name__ == "__main__":
    main()
