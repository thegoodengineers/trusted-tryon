"""Measure try-on latency through our real pipeline (upload, API, checks, retry, cache) and write results/.

  python bench.py              # mock (no key): measures our own overhead only, labelled "mock"
  python bench.py --real --n 1 # live API; needs HTF_TRYON_API_KEY. Each garment costs up to 2 credits per round.

Writes results/latency.csv (one row per try-on, appended) and results/LATENCY.md (summary of all rows).
Never hand-edit those files: every number in them comes from a run of this script.
"""
import argparse
import csv
import datetime
import os
import platform
import statistics
import subprocess
import time

from fastapi.testclient import TestClient

HERE = os.path.dirname(os.path.abspath(__file__))
FIELDS = ["when", "commit", "machine", "mode", "model", "garment", "photo_upload_s", "server_total_s", "wall_s",
          "attempts", "verdict", "colour_score", "cached_repeat_s", "polls", "http_retries"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--real", action="store_true", help="use the live API (HTF_TRYON_API_KEY must be set)")
    ap.add_argument("--n", type=int, default=3, help="rounds over all garments")
    ap.add_argument("--garments", default="", help="comma-separated ids (default: all)")
    args = ap.parse_args()
    if args.real and not os.environ.get("HTF_TRYON_API_KEY"):
        raise SystemExit("Set HTF_TRYON_API_KEY first (see README).")
    if not args.real:
        os.environ.pop("HTF_TRYON_API_KEY", None)
        os.environ.setdefault("HTF_MOCK_DELAY", "0")
    os.chdir(HERE)
    import app as server  # imported after the env is set, so it picks mock or live

    web = TestClient(server.app)
    garments = args.garments.split(",") if args.garments else list(server.CATALOG)
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip() or "none"
    machine = f"{platform.system()}-{platform.machine()}-{platform.node()[:12]}"
    rows = []
    for r in range(args.n):
        for model in ("asha", "ravi"):
            photo = open(f"static/models/{model}.png", "rb").read()
            t = time.perf_counter()
            up = web.post("/api/photo", files={"photo": ("p.png", photo, "image/png")}, data={"consent": "true", "adult": "true"})
            up.raise_for_status()
            sid, upload_s = up.json()["session"], time.perf_counter() - t
            for gid in garments:
                t = time.perf_counter()
                job = web.post("/api/tryon", json={"session": sid, "garment": gid}).json()["job"]
                while not (j := web.get(f"/api/tryon/{job}").json())["done"]:
                    time.sleep(0.2)
                wall = time.perf_counter() - t
                t = time.perf_counter()
                job2 = web.post("/api/tryon", json={"session": sid, "garment": gid}).json()["job"]
                assert web.get(f"/api/tryon/{job2}").json()["cached"]
                cached = time.perf_counter() - t
                row = {"when": datetime.datetime.now().isoformat(timespec="seconds"), "commit": commit, "machine": machine,
                       "mode": server.client.mode, "model": model, "garment": gid, "photo_upload_s": round(upload_s, 3),
                       "server_total_s": j.get("total_seconds"), "wall_s": round(wall, 3), "attempts": len(j.get("attempts", [])),
                       "verdict": j.get("verdict") or j.get("error", {}).get("code"), "colour_score": j.get("colour_score"),
                       "cached_repeat_s": round(cached, 4), "polls": sum(a.get("polls", 0) for a in j.get("attempts", [])),
                       "http_retries": sum(a.get("http_retries", 0) for a in j.get("attempts", []))}
                rows.append(row)
                print(row)
            web.delete(f"/api/session/{sid}")
    os.makedirs("results", exist_ok=True)
    path = "results/latency.csv"
    new = not os.path.exists(path)
    with open(path, "a", newline="") as f:
        w = csv.DictWriter(f, FIELDS)
        if new:
            w.writeheader()
        w.writerows(rows)
    summarise(path)


def summarise(path):
    rows = list(csv.DictReader(open(path)))
    out = ["# Try-on latency", "", "Generated by `python bench.py` from `results/latency.csv`. Do not edit by hand.", "",
           "| Mode | Try-ons | Median wall (s) | p90 wall (s) | Median cached repeat (s) | Shown first time | Retried and passed | Held back | Errors |",
           "|---|---|---|---|---|---|---|---|---|"]
    for mode in sorted({r["mode"] for r in rows}):
        rs = [r for r in rows if r["mode"] == mode]
        walls = sorted(float(r["wall_s"]) for r in rs)
        p90 = walls[min(len(walls) - 1, int(0.9 * len(walls)))]
        count = lambda v: sum(r["verdict"] == v for r in rs)
        errors = len(rs) - count("shown") - count("retried") - count("held back")
        out.append(f"| {mode} | {len(rs)} | {statistics.median(walls):.2f} | {p90:.2f} | "
                   f"{statistics.median(float(r['cached_repeat_s']) for r in rs):.4f} | {count('shown')} | {count('retried')} | "
                   f"{count('held back')} | {errors} |")
    out += ["", "Mock rows measure only our own pipeline (upload, checks, retry, cache) around a paste-on stand-in, "
            "plus a deliberate colour fault on the kurta's first try. They say nothing about the real API's speed or accuracy.",
            "", f"Last run: {rows[-1]['when']} on {rows[-1]['machine']}, commit {rows[-1]['commit']}."]
    open("results/LATENCY.md", "w").write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
